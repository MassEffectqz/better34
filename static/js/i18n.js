const DICTS = { ru: RU, en: EN };

let lang = 'ru';
try {
  const saved = localStorage.getItem('briefly_lang');
  if (saved === 'ru' || saved === 'en') lang = saved;
  else if (!saved && (navigator.language || '').toLowerCase().startsWith('en')) lang = 'en';
} catch { /* noop */ }

/**
 * Перевод ключа с опциональной подстановкой параметров ({hotkey} и т.п.).
 * Ранее params молча игнорировались — тултипы показывали «Лайк ({hotkey})».
 * @param {string} key
 * @param {Object<string, string|number>} [params]
 * @returns {string}
 */
function t(key, params) {
  let s = DICTS[lang][key] ?? DICTS.ru[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}

/** tf — синоним t с явным намерением подстановки. @param {string} key @param {Object<string, string|number>} [params] @returns {string} */
function tf(key, params) {
  return t(key, params);
}

/**
 * Числовые формы: 1 пост / 2 поста / 5 постов. Ключ хранит три формы с
 * суффиксами 1/2/5 (1 пост, 2 поста, 5 постов). Английский не различает, у
 * него формы совпадают, поэтому подставляется любая.
 * @param {string} base базовый ключ, например 'tagPreview.posts'
 * @param {number} n
 * @returns {string}
 */
function tp(base, n) {
  const num = Math.abs(Number(n) || 0);
  const hundreds = num % 100;
  const units = num % 10;
  let form = '5';
  if (hundreds > 10 && hundreds < 20) form = '5';
  else if (units === 1) form = '1';
  else if (units >= 2 && units <= 4) form = '2';
  return t(`${base}${form}`, { n: n });
}

function applyI18n(root) {
  const host = root || document;
  host.querySelectorAll('[data-i18n]').forEach(el => {
    const v = t(el.dataset.i18n);
    if (typeof v === 'string') el.textContent = v;
  });
  host.querySelectorAll('[data-i18n-ph]').forEach(el => {
    el.placeholder = t(el.dataset.i18nPh);
  });
  host.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.title = t(el.dataset.i18nTitle);
  });
  host.querySelectorAll('[data-i18n-aria]').forEach(el => {
    el.setAttribute('aria-label', t(el.dataset.i18nAria));
  });
}

function getLang() { return lang; }

// Классические скрипты (sw-register.js грузится без module) не могут импортировать
// i18n.js — публикуем t() в window. Модули по-прежнему используют импорт.
if (typeof window !== 'undefined') /** @type {any} */ (window).__brieflyT = t;

function setLang(next) {
  if (next !== 'ru' && next !== 'en') return;
  lang = next;
  try { localStorage.setItem('briefly_lang', lang); } catch { /* noop */ }
  applyI18n();
  document.documentElement.lang = lang;
  window.dispatchEvent(new CustomEvent('briefly-lang', { detail: lang }));
}

export { t, tf, tp, getLang, setLang, applyI18n };
