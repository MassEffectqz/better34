function icon(name, size, solid) {
  const inner = ICONS[name];
  if (!inner) return '';
  const wh = size ? ` width="${size}" height="${size}"` : '';
  return `<svg${wh} viewBox="0 0 24 24" fill="${solid ? 'currentColor' : 'none'}" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${inner}</svg>`;
}

function renderLucideIcons(root) {
  (root || document).querySelectorAll('[data-lucide]').forEach(el => {
    const svg = icon(el.dataset.lucide, parseInt(el.dataset.size, 10) || 16, el.dataset.solid === '1');
    if (!svg) return;
    const tmp = document.createElement('div');
    tmp.innerHTML = svg;
    const node = tmp.firstChild;
    if (el.className) (/** @type {Element} */ (node)).setAttribute('class', el.className);
    el.replaceWith(node);
  });
}

