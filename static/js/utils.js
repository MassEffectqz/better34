const HISTORY_KEY = 'briefly_search_history';
// v2: [{q, count, pin}]; legacy-формат (строки) мигрируется на лету.
function getHistory() {
  try {
    const raw = JSON.parse(localStorage.getItem(HISTORY_KEY)) || [];
    return raw
      .map(e => typeof e === 'string'
        ? { q: e, count: 1, pin: false }
        : { q: String(e.q || ''), count: Math.max(1, e.count | 0), pin: !!e.pin })
      .filter(x => x.q);
  } catch { return []; }
}
function saveHistory(list) { try { localStorage.setItem(HISTORY_KEY, JSON.stringify(list)); } catch {} }
function addHistory(q) {
  if (!q) return;
  const h = getHistory();
  const ex = h.find(x => x.q === q);
  if (ex) ex.count++;
  else h.unshift({ q, count: 1, pin: false });
  saveHistory(h.slice(0, 30));
}
function removeHistory(q) { saveHistory(getHistory().filter(x => x.q !== q)); }
function togglePinHistory(q) {
  const h = getHistory();
  const e = h.find(x => x.q === q);
  if (!e) return false;
  e.pin = !e.pin;
  saveHistory(h);
  return e.pin;
}
// Очистка оставляет закреплённые запросы.
function clearHistory() { saveHistory(getHistory().filter(x => x.pin)); }

